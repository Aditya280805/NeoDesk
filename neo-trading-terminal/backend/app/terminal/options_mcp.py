"""Private Streamable HTTP MCP server, sharing the terminal's broker sessions.

Capabilities are generated by trusted backend code, never by the model. Every
HTTP request (including initialization and discovery) checks their lifetime.
"""
import asyncio
import json
import logging
import secrets
import socket
import time
from contextlib import asynccontextmanager, nullcontext
from dataclasses import dataclass, field

import uvicorn
from fastapi import HTTPException
from starlette.responses import JSONResponse

from app.terminal.options_snapshot import OptionsContext
from app.terminal.portfolio_risk_contracts import RiskPolicy
from app.terminal.portfolio_risk_diagnostics import risk_diagnostics

logger = logging.getLogger(__name__)
TOOL_VERSION = '1'
PORTFOLIO_SCOPES = frozenset(('portfolio', 'portfolio_analysis', 'risk'))


@dataclass
class Capability:
    user_id: int
    context: OptionsContext | None
    run_id: str
    expires: float
    scope: str = 'chain'
    session_generation: str | None = None
    force_refresh: bool = False
    deadline_monotonic: float = field(default_factory=lambda: time.monotonic() + 60)
    allowed_tools: frozenset[str] = field(init=False)
    risk_policy: RiskPolicy | None = None
    calls: int = 0
    snapshot_json: str | None = None
    selected_report: dict | None = None
    risk_diagnostic: dict | None = None
    harness: object | None = field(default=None, repr=False)
    lock: asyncio.Lock = field(default_factory=asyncio.Lock)
    analytics_json: dict[str, str] = field(default_factory=dict, repr=False)
    analytics_budget: object | None = field(default=None, repr=False)

    def bind_analytics(self, evidence, budget):
        from .analytics_contracts import AnalyticsEvidence
        from .analytics_runtime import TOOLS_BY_ROLE, TurnBudget
        roles = {'chain':'options_trading_analysis','portfolio_analysis':'portfolio_analysis','risk':'portfolio_risk'}
        role = roles.get(self.scope)
        if self.analytics_budget is not None or not isinstance(budget,TurnBudget) or role is None or not evidence or not set(evidence) <= TOOLS_BY_ROLE[role]:
            raise ValueError('Invalid analytics capability binding')
        if not self.session_generation or not isinstance(self.user_id,int) or isinstance(self.user_id,bool) or self.user_id <= 0:
            raise ValueError('Authenticated live session required')
        captured = {name:AnalyticsEvidence.model_validate(value.model_dump() if isinstance(value,AnalyticsEvidence) else value).model_dump_json() for name,value in evidence.items()}
        self.analytics_json, self.analytics_budget = captured, budget
        self.allowed_tools = frozenset(captured)


    def __post_init__(self):
        names = {'chain': 'get_option_snapshot', 'portfolio': 'get_portfolio_snapshot'}
        names.update(portfolio_analysis='get_portfolio_analysis_snapshot', risk='get_portfolio_risk_report')
        names.update({kind:f'get_{kind}_report' for kind in ('strategy','scan','alert','backtest')})
        if self.scope not in names:
            raise ValueError('Invalid capability scope')
        self.allowed_tools = frozenset([names[self.scope]])


class CapabilityAuth:
    def __init__(self, app, runtime):
        self.app, self.runtime = app, runtime

    async def __call__(self, scope, receive, send):
        if scope['type'] != 'http':
            return await self.app(scope, receive, send)
        headers = dict(scope.get('headers', []))
        auth = headers.get(b'authorization', b'').decode('latin1')
        token = auth[7:] if auth.startswith('Bearer ') else ''
        capability = self.runtime.capabilities.get(token)
        origin = headers.get(b'origin')
        if not capability or capability.expires <= time.monotonic() or origin:
            return await JSONResponse({'detail': 'Invalid internal capability.'}, status_code=401)(scope, receive, send)
        scope['options_capability'] = capability
        return await self.app(scope, receive, send)


class InternalServer(uvicorn.Server):
    # The public Uvicorn process owns signal handling, not this inner listener.
    def capture_signals(self):
        return nullcontext()


class MCPConnection:
    def __init__(self, tools, token, capability=None):
        self.tools, self.token = tools, token
        self.capability = capability

    @property
    def risk_diagnostic(self):
        return self.capability.risk_diagnostic if self.capability else None

    async def snapshot(self):
        return await self._snapshot('get_option_snapshot')

    async def portfolio_snapshot(self):
        return await self._snapshot('get_portfolio_snapshot')

    async def _snapshot(self, name):
        result = await self.tools.session.call_tool(name, {})
        if getattr(result, 'is_error', getattr(result, 'isError', False)):
            detail = ('Portfolio evidence could not be retrieved or validated. Refresh your Kotak connection.'
                if name == 'get_portfolio_snapshot' else
                'The option chain could not be retrieved or validated. Check your Kotak connection and market selection.')
            raise HTTPException(503, detail)
        # FastMCP Client and SDK ClientSession both expose content text blocks.
        return json.loads(next(block.text for block in result.content if block.type == 'text'))


class OptionsMCP:
    def __init__(self, snapshots, port=8766, *, portfolio_service=None):
        self.snapshots, self.port = snapshots, port
        self.portfolio_service = portfolio_service
        self.capabilities = {}
        self.pending = {}
        self.server = None
        self.task = None
        self.url = None

    @property
    def ready(self):
        return bool(self.server and self.server.started and self.task and not self.task.done())

    async def _work(self, capability, function, *args, coroutine=None, **kwargs):
        if capability.user_id in self.pending:
            if coroutine is not None: coroutine.close()
            raise ValueError('Broker request already running')
        if len(self.pending) >= 4:
            if coroutine is not None: coroutine.close()
            raise ValueError('Broker capacity exhausted')
        task = asyncio.create_task(coroutine if coroutine is not None else asyncio.to_thread(function, *args, **kwargs))
        self.pending[capability.user_id] = task
        def finished(work):
            if self.pending.get(capability.user_id) is work:
                self.pending.pop(capability.user_id, None)
            if not work.cancelled(): work.exception()
        task.add_done_callback(finished)
        return await asyncio.shield(task)

    async def _read_analytics(self, capability, name):
        from .analytics_contracts import AnalyticsEvidence
        async with capability.lock:
            if name not in capability.allowed_tools or name not in capability.analytics_json or capability.analytics_budget is None:
                raise ValueError('Tool unavailable for this request')
            if min(capability.expires,capability.deadline_monotonic) <= time.monotonic() or not capability.session_generation or self.portfolio_service is None:
                raise ValueError('Live analytics capability expired')
            role = {'chain':'options_trading_analysis','portfolio_analysis':'portfolio_analysis','risk':'portfolio_risk'}[capability.scope]
            capability.analytics_budget.consume(role)
            remaining = min(10,capability.analytics_budget.deadline-time.monotonic(),capability.deadline_monotonic-time.monotonic())
            async with asyncio.timeout(max(0,remaining)):
                await self._work(capability,self.portfolio_service.assert_generation,capability.user_id,
                                 capability.session_generation,deadline_monotonic=capability.deadline_monotonic)
            return AnalyticsEvidence.model_validate_json(capability.analytics_json[name]).model_dump(mode='json')

    async def _validate_analytics_discovery(self, capability):
        if capability.analytics_budget is None:
            return
        remaining = min(10,capability.expires-time.monotonic(),capability.deadline_monotonic-time.monotonic(),capability.analytics_budget.deadline-time.monotonic())
        if remaining<=0 or not capability.session_generation or self.portfolio_service is None:
            raise ValueError('Analytics session unavailable')
        async with asyncio.timeout(remaining):
            await self._work(capability,self.portfolio_service.assert_generation,capability.user_id,
                capability.session_generation,deadline_monotonic=capability.deadline_monotonic)

    async def _read(self, capability):
        async with capability.lock:
            if capability.expires <= time.monotonic():
                raise ValueError('Expired capability')
            if capability.deadline_monotonic <= time.monotonic():
                raise ValueError('Request deadline expired')
            if capability.scope in PORTFOLIO_SCOPES:
                if self.portfolio_service is None or not capability.session_generation:
                    raise ValueError('Portfolio unavailable')
                await self._work(capability, self.portfolio_service.assert_generation, capability.user_id, capability.session_generation, deadline_monotonic=capability.deadline_monotonic)
                if capability.deadline_monotonic <= time.monotonic():
                    raise ValueError('Request deadline expired')
            capability.calls += 1
            if capability.harness:
                capability.harness.read_tool()
            # One prefetch plus two model tool calls. Hard server-side bound.
            if capability.calls > 3:
                raise ValueError('Tool budget exhausted')
            if capability.snapshot_json is None:
                if capability.scope in ('strategy','scan','alert','backtest'):
                    raise ValueError('Captured saved report required')
                if capability.user_id in self.pending:
                    raise ValueError('Broker request already running')
                if len(self.pending) >= 4:
                    raise ValueError('Broker capacity exhausted')
                if capability.scope in PORTFOLIO_SCOPES:
                    work = asyncio.to_thread(self.portfolio_service.fetch, capability.user_id,
                        expected_generation=capability.session_generation, force=capability.force_refresh,
                        deadline_monotonic=capability.deadline_monotonic)
                else:
                    work = asyncio.to_thread(self.snapshots.fetch, capability.user_id, capability.context)
                if capability.harness:
                    capability.harness.broker_fetches += 1
                snapshot = await self._work(capability, lambda: None, coroutine=work)
                if capability.deadline_monotonic <= time.monotonic():
                    raise ValueError('Request deadline expired')
                if capability.scope in PORTFOLIO_SCOPES:
                    from app.terminal.portfolio_risk_contracts import PortfolioRiskEnvelope
                    from app.terminal.portfolio_risk import evaluate_portfolio_risk
                    from datetime import UTC, datetime
                    await self._work(capability, self.portfolio_service.assert_generation, capability.user_id, capability.session_generation, deadline_monotonic=capability.deadline_monotonic)
                    if capability.deadline_monotonic <= time.monotonic():
                        raise ValueError('Request deadline expired')
                    if capability.risk_policy is None:
                        raise ValueError('Captured policy required')
                    evaluation_started = time.monotonic()
                    try:
                        report = evaluate_portfolio_risk(snapshot, capability.risk_policy, datetime.now(UTC))
                    except Exception:
                        diagnostic = risk_diagnostics(None, (time.monotonic() - evaluation_started) * 1000,
                            failure_stage='evaluation', evidence_id=snapshot.evidence_id, policy=capability.risk_policy)
                        capability.risk_diagnostic = diagnostic
                        logger.info('portfolio_risk %s', json.dumps(diagnostic, allow_nan=False))
                        raise ValueError('Risk evaluation unavailable.') from None
                    diagnostic = risk_diagnostics(report, (time.monotonic() - evaluation_started) * 1000)
                    capability.risk_diagnostic = diagnostic
                    logger.info('portfolio_risk %s', json.dumps(diagnostic, allow_nan=False))
                    envelope = PortfolioRiskEnvelope(**snapshot.model_dump(), risk_report=report)
                    serialized = PortfolioRiskEnvelope.model_validate_json(envelope.model_dump_json()).model_dump_json()
                    if capability.deadline_monotonic <= time.monotonic():
                        raise ValueError('Request deadline expired')
                    capability.snapshot_json = serialized
                else:
                    capability.snapshot_json = json.dumps(snapshot, allow_nan=False)
            elif capability.harness:
                capability.harness.cache_hits += 1
            result = json.loads(capability.snapshot_json)
            if capability.scope == 'portfolio_analysis':
                from app.terminal.portfolio_contracts import PortfolioSnapshot
                result.pop('risk_report', None)
                # Risk-only broker inputs are not part of analysis evidence.
                result.pop('risk_inputs', None)
                result = PortfolioSnapshot.model_validate(result).model_dump(mode='json')
            elif capability.scope == 'risk':
                result = {'evidence_id': result['evidence_id'], 'risk_report': result['risk_report']}
            if capability.deadline_monotonic <= time.monotonic():
                raise ValueError('Request deadline expired')
            return result

    @asynccontextmanager
    async def lifespan(self):
        # Multiple application clients can share one app instance. Only the
        # lifespan that created the listener owns its shutdown and event loop.
        if self.ready:
            yield self
            return
        self.server, self.task = None, None
        sock = None
        try:
            from fastmcp import FastMCP
            from fastmcp.exceptions import ToolError
            from fastmcp.server.dependencies import get_http_request
            from starlette.middleware import Middleware
            from fastmcp.server.middleware import Middleware as MCPMiddleware

            class ScopeMiddleware(MCPMiddleware):
                async def on_list_tools(self, context, call_next):
                    capability = get_http_request().scope['options_capability']
                    try:
                        await self_runtime._validate_analytics_discovery(capability)
                    except Exception:
                        raise ToolError('Analytics session unavailable.') from None
                    return [tool for tool in await call_next(context) if tool.name in capability.allowed_tools]

                async def on_call_tool(self, context, call_next):
                    capability = get_http_request().scope['options_capability']
                    if context.message.name not in capability.allowed_tools or context.message.arguments:
                        raise ToolError('Tool unavailable for this request.')
                    return await call_next(context)

            self_runtime = self
            mcp = FastMCP('NeoDesk Options', version=TOOL_VERSION,
                          mask_error_details=True, strict_input_validation=True)
            mcp.add_middleware(ScopeMiddleware())

            @mcp.tool(annotations={'readOnlyHint': True, 'destructiveHint': False, 'openWorldHint': False})
            async def get_option_snapshot() -> dict:
                """Read the selected option chain, OI summary, provenance and limitations for this request."""
                try:
                    return await self._read(get_http_request().scope['options_capability'])
                except Exception:
                    # FastMCP may log tool exceptions. Do not give it provider text.
                    raise ValueError('Option snapshot unavailable or request budget exhausted.') from None

            @mcp.tool(annotations={'readOnlyHint': True, 'destructiveHint': False, 'openWorldHint': False})
            async def get_portfolio_snapshot() -> dict:
                """Read immutable portfolio evidence for the signed-in user and this request."""
                try:
                    return await self._read(get_http_request().scope['options_capability'])
                except Exception:
                    raise ValueError('Portfolio snapshot unavailable or request budget exhausted.') from None

            async def saved_report():
                try:
                    return await self._read(get_http_request().scope['options_capability'])
                except Exception:
                    raise ValueError('Saved report unavailable or request budget exhausted.') from None
            for name in ('get_portfolio_analysis_snapshot', 'get_portfolio_risk_report'):
                mcp.tool(name=name, description='Read only the authorized immutable specialist evidence for this request; no arguments.',
                    annotations={'readOnlyHint':True,'destructiveHint':False,'openWorldHint':False})(saved_report)
            for kind in ('strategy','scan','alert','backtest'):
                mcp.tool(name=f'get_{kind}_report', description='Read the immutable report selected by the authenticated application; no arguments.',
                    annotations={'readOnlyHint':True,'destructiveHint':False,'openWorldHint':False})(saved_report)

            from .analytics_runtime import TOOLS_BY_ROLE
            def analytics_reader(name):
                async def read() -> dict:
                    try:
                        return await self._read_analytics(get_http_request().scope['options_capability'],name)
                    except Exception:
                        raise ValueError('Analytics evidence unavailable or request budget exhausted.') from None
                return read
            for name in sorted(set().union(*TOOLS_BY_ROLE.values())):
                mcp.tool(name=name,description='Read captured deterministic role-scoped analytics and candidate proposals; unavailable metrics are explicit. No arguments.',
                    annotations={'readOnlyHint':True,'destructiveHint':False,'openWorldHint':False})(analytics_reader(name))

            app = mcp.http_app(path='/mcp', stateless_http=True, json_response=True,
                               middleware=[Middleware(CapabilityAuth, runtime=self)])
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.bind(('127.0.0.1', self.port))
            sock.listen(128)
            sock.setblocking(False)
            self.url = f'http://127.0.0.1:{sock.getsockname()[1]}/mcp'
            self.server = InternalServer(uvicorn.Config(app, log_config=None, access_log=False,
                log_level='critical', lifespan='on', timeout_graceful_shutdown=2, proxy_headers=False))
            self.task = asyncio.create_task(self.server.serve(sockets=[sock]))
            async with asyncio.timeout(10):
                while not self.server.started:
                    if self.task.done():
                        await self.task
                        raise RuntimeError('Listener stopped during startup')
                    await asyncio.sleep(.01)
        except Exception:
            logger.warning('Options MCP unavailable: startup failed (details suppressed).')
            if self.task:
                self.task.cancel()
                await asyncio.gather(self.task, return_exceptions=True)
            self.server = None
            if sock:
                sock.close()
        try:
            yield self
        finally:
            self.capabilities.clear()
            if self.server and self.task:
                self.server.should_exit = True
                try:
                    await asyncio.wait_for(asyncio.shield(self.task), 5)
                except (TimeoutError, asyncio.CancelledError):
                    self.task.cancel()
                    await asyncio.gather(self.task, return_exceptions=True)
            if sock:
                sock.close()

    @asynccontextmanager
    async def connection(self, user_id, context, run_id, *, scope='chain', session_generation=None, force_refresh=False, deadline_monotonic=None, risk_policy=None, selected_report=None, harness=None, analytics_evidence=None, analytics_budget=None):
        if not self.ready:
            raise HTTPException(503, 'Options monitoring is unavailable. The internal MCP service is not ready.')
        from agno.tools.mcp import MCPTools
        from agno.tools.mcp.params import StreamableHTTPClientParams
        token = secrets.token_urlsafe(32)
        if scope in PORTFOLIO_SCOPES and not isinstance(risk_policy, RiskPolicy):
            raise ValueError('Portfolio requires captured risk policy')
        if scope in PORTFOLIO_SCOPES and (context is not None or not session_generation):
            raise ValueError('Portfolio requires captured session generation and no chain context')
        if scope == 'chain' and not isinstance(context, OptionsContext):
            raise ValueError('Chain requires selected context')
        capability = Capability(user_id, context.model_copy(deep=True) if context is not None else None,
            run_id, time.monotonic() + 65, scope=scope, session_generation=session_generation, force_refresh=force_refresh, risk_policy=risk_policy,
            deadline_monotonic=deadline_monotonic if deadline_monotonic is not None else time.monotonic()+60)
        capability.harness = harness
        if analytics_evidence is not None:
            capability.bind_analytics(analytics_evidence,analytics_budget)
        if scope in ('strategy','scan','alert','backtest'):
            if context is not None or session_generation is not None or not selected_report or selected_report.get('report_kind') != scope:
                raise ValueError('Captured selected report required')
            from app.terminal.options_report_context import bounded_report
            capability.snapshot_json = json.dumps(bounded_report(selected_report), allow_nan=False)
        self.capabilities[token] = capability
        try:
            async with MCPTools(url=self.url, transport='streamable-http',
                headers={'Authorization': 'Bearer '+token},
                include_tools=sorted(capability.allowed_tools), timeout_seconds=55,
                server_params=StreamableHTTPClientParams(url=self.url, timeout=10, sse_read_timeout=55)) as tools:
                yield MCPConnection(tools, token, capability)
        finally:
            self.capabilities.pop(token, None)
